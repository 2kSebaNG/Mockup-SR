import type { components } from './api/schema';

export type AttachmentDocumentType = components['schemas']['AttachmentDocumentType'];

export const DOCUMENT_TYPE_LABEL: Record<AttachmentDocumentType, string> = {
  QUOTE: 'Cotización',
  PURCHASE_ORDER_PDF: 'OC generada',
  TRANSFER_RECEIPT: 'Comprobante de transferencia',
  DISPATCH_GUIDE: 'Guía de despacho',
  MANUAL: 'Manual / ficha técnica',
  INVOICE: 'Factura',
  EMAIL_BACKUP: 'Correo de respaldo',
  OTHER: 'Otro',
};

/** Order the document checklist shows them in — mirrors the real process (section
 * 2.5, 8): cotización, luego la OC, comprobante, guía/manual, factura, correos. */
export const CHECKLIST_ORDER: AttachmentDocumentType[] = [
  'QUOTE',
  'PURCHASE_ORDER_PDF',
  'TRANSFER_RECEIPT',
  'DISPATCH_GUIDE',
  'MANUAL',
  'INVOICE',
  'EMAIL_BACKUP',
];

/** "1 o 2 archivos que pueden ser guía de despacho o manual" — optional by nature,
 * never expected to always be present. PURCHASE_ORDER_PDF is generated by the system
 * itself, so it isn't something Procurement is ever "missing". */
export const OPTIONAL_CHECKLIST_TYPES = new Set<AttachmentDocumentType>([
  'DISPATCH_GUIDE',
  'MANUAL',
  'PURCHASE_ORDER_PDF',
]);

/** What actually blocks "Marcar como pagada" — mirrors
 * PurchaseOrdersService.markPaid exactly. The invoice doesn't gate it: it doesn't
 * always arrive on time and shouldn't hold up a payment that already happened. */
export const REQUIRED_FOR_PAYMENT: AttachmentDocumentType = 'TRANSFER_RECEIPT';

export interface ChecklistRow<A extends { documentType?: AttachmentDocumentType | null }> {
  documentType: AttachmentDocumentType;
  label: string;
  optional: boolean;
  files: A[];
}

/** Buckets a flat attachment list into the checklist's fixed rows, in display order
 * — an attachment with no documentType (predates the column) or an unrecognized one
 * falls into OTHER rather than disappearing. */
export function buildDocumentChecklist<A extends { documentType?: AttachmentDocumentType | null }>(
  attachments: A[],
): ChecklistRow<A>[] {
  const byType = new Map<AttachmentDocumentType, A[]>();
  for (const attachment of attachments) {
    const type = attachment.documentType ?? 'OTHER';
    const bucket = byType.get(type) ?? [];
    bucket.push(attachment);
    byType.set(type, bucket);
  }
  return CHECKLIST_ORDER.map((documentType) => ({
    documentType,
    label: DOCUMENT_TYPE_LABEL[documentType],
    optional: OPTIONAL_CHECKLIST_TYPES.has(documentType),
    files: byType.get(documentType) ?? [],
  }));
}
