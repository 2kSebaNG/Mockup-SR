/** The regions' names, from north to south. */
export const REGIONS: string[] = TERRITORY.map((region) => region.name);

/** The names of the comunas of a region, alphabetically; none for a region that is not one of the
 * 16 (blank, or free text saved before regions were a list). */
export function comunasOf(region: string): string[] {
  return TERRITORY.find((item) => item.name === region)?.comunas.map((comuna) => comuna.name) ?? [];
}

/**
 * The comuna to keep when the region is changed: the same one if it is a comuna of the new region,
 * none otherwise (a comuna of another region would contradict it). Only used when a person changes
 * the region: a comuna saved earlier as free text stays untouched until then.
 */
export function reconcileComuna(region: string, comuna: string): string {
  return comunasOf(region).includes(comuna) ? comuna : '';
}

/** The region a comuna belongs to, by its name, when it is one of the 346. */
export function regionOfComuna(comuna: string): string | undefined {
  return TERRITORY.find((region) => region.comunas.some((item) => item.name === comuna))?.name;
}
