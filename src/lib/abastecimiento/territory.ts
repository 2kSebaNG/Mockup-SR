/**
 * The regions and comunas of Chile: 16 regions and 346 comunas (the division in force since Ñuble
 * was created in 2018), each comuna with its official territorial code (CUT, from SUBDERE) and each
 * region with its ISO 3166-2 code. The division changes once in decades, so it is kept here rather
 * than asked for at run time: nothing to fail when a form opens.
 *
 * The data comes from the MIT-licensed package `chilean-territorial-divisions` 1.0.1 (Hans Steven
 * Vergara Chamorro), with five comuna names corrected (Paihuano, Rinconada, Marchigüe, Ránquil and
 * San Nicolás, which it had misspelled or cut short) after checking every name against Wikipedia's
 * table of comunas by code. The totals are checked against the official ones by `territory.spec.ts`.
 * The regions keep the names the vendor form already used, so what is saved still matches.
 */
export interface Comuna {
  name: string;
  /** The official code (CUT), e.g. "13101" for Santiago. */
  code: string;
}

export interface Region {
  name: string;
  /** ISO 3166-2, e.g. "CL-RM". */
  iso: string;
  /** In alphabetical order. */
  comunas: Comuna[];
}

